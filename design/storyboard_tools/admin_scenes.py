def DV(robots, progress, *alerts, op=None, dialog=None, modal=None, toast=None, closing=False, mark=None):
    """운영 모드 줄이 있는 현황 (v1.4). 지도 자리는 운영 모드 줄 때문에 뺌. op: dev | entering | test."""
    body = [('nomap',), ('robots', robots), ('progress', progress), *alerts]
    if dialog:
        body.append(('dialog2', *dialog))
    if modal:
        body.append(('modal', *modal))
    if toast:
        body.append(('toast', toast))
    return {'kind': 'dashboard', 'mode': R, 'op': op, 'closing': closing, 'mark': mark, 'body': body}

