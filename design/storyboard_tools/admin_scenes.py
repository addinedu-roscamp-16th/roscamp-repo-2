def L(admin, system, basis):
    return [f'관리자: {admin}', f'시스템: {system}', f'근거: {basis}']


def D(robots, progress, *alerts, **kw):
    return {'kind': 'dashboard', 'mode': kw.get('mode', R), 'mark': kw.get('mark'), 'mode_off': kw.get('mode_off', False),
            'body': [('robots', robots), ('progress', progress), *alerts]}


def O(filt, *rows, **kw):
    return {'kind': 'orders', 'mode': kw.get('mode', R), 'mode_off': kw.get('mode_off', False), 'badge': kw.get('badge', 0),
            'body': [('filter', filt), *rows]}


def RB(*rows, **kw):
    """로봇 화면. 버튼 앞 '~'는 꺼진 버튼."""
    return {'kind': 'robots', 'mode': kw.get('mode', R), 'mode_off': kw.get('mode_off', False), 'badge': kw.get('badge', 0),
            'body': [('filter', '로봇 · 상태 · 맡은 주문 · 오류 · 락'), *rows]}


